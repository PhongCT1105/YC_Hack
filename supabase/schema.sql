-- Node contribution summary — how many agents endorsed vs disputed each node
CREATE VIEW node_consensus AS
SELECT
  n.id                                          AS node_id,
  n.job_id,
  n.type,
  n.title,
  n.content,
  n.confidence,
  COUNT(*) FILTER (WHERE ac.contribution_type = 'created')   AS created_by,
  COUNT(*) FILTER (WHERE ac.contribution_type = 'endorsed')  AS endorsements,
  COUNT(*) FILTER (WHERE ac.contribution_type = 'disputed')  AS disputes,
  COUNT(*) FILTER (WHERE ac.contribution_type = 'refined')   AS refinements,
  -- Agents that endorsed this node (array of perspectives)
  ARRAY_AGG(DISTINCT a.perspective) FILTER (
    WHERE ac.contribution_type IN ('created', 'endorsed')
  )                                             AS endorsing_perspectives
FROM context_nodes n
LEFT JOIN agent_contributions ac ON ac.node_id = n.id
LEFT JOIN agents a ON a.id = ac.agent_id
GROUP BY n.id;

-- Graph edge summary for a job — useful for frontend graph rendering
CREATE VIEW graph_edges_view AS
SELECT
  e.id,
  e.job_id,
  e.type,
  e.weight,
  src.id    AS source_id,
  src.type  AS source_type,
  src.title AS source_title,
  tgt.id    AS target_id,
  tgt.type  AS target_type,
  tgt.title AS target_title
FROM context_edges e
JOIN context_nodes src ON src.id = e.source_node_id
JOIN context_nodes tgt ON tgt.id = e.target_node_id;
